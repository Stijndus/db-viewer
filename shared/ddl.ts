import { qualifiedName, quoteIdent, stringLiteral } from './dialect';
import type { DbType } from './models';

/**
 * Structure changes as SQL, per dialect: add, change and drop a column, create and drop an index,
 * create a table. The statements are shown before they run. Names are always quoted; a type and a
 * default are SQL the user types (as in HeidiSQL), so they go in as written.
 */

export interface ColumnDef {
  name: string;
  /** e.g. `varchar(100)`, `int`, `decimal(10,2)`. */
  type: string;
  nullable: boolean;
  /** SQL for the default (`0`, `'tekst'`, `CURRENT_TIMESTAMP`); empty: no default. */
  defaultValue: string;
  /** AUTO_INCREMENT / IDENTITY / generated by default as identity. */
  autoIncrement: boolean;
  /** MySQL and PostgreSQL only. */
  comment: string;
}

export interface IndexInfo {
  name: string;
  columns: string[];
  unique: boolean;
  primary: boolean;
}

export interface IndexDef {
  name: string;
  columns: string[];
  unique: boolean;
}

/** What a dialect can change in place; SQLite only renames a column (the rest needs a rebuild). */
export function canAlterColumn(dialect: DbType): boolean {
  return dialect !== 'sqlite';
}

export function hasComments(dialect: DbType): boolean {
  return dialect === 'mysql' || dialect === 'postgres';
}

