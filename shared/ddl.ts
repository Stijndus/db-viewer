function check(def: ColumnDef): void {
  if (!def.name.trim()) throw new Error('Geef de kolom een naam.');
  if (!def.type.trim()) throw new Error(`Geef kolom ${def.name} een type.`);
  // The type is SQL as typed, but one statement only.
  if (/;|--|\/\*/.test(def.type) || /;|--|\/\*/.test(def.defaultValue)) {
    throw new Error('Een type of standaardwaarde kan geen ; of commentaar bevatten.');
  }
}

/** The part after the name in CREATE TABLE / ADD COLUMN. */
function columnBody(def: ColumnDef, dialect: DbType, inCreate: boolean, primary = false): string {
  const parts = [def.type.trim()];
  if (def.autoIncrement) {
    if (dialect === 'mysql') parts.push('AUTO_INCREMENT');
    if (dialect === 'postgres') parts.push('GENERATED BY DEFAULT AS IDENTITY');
    if (dialect === 'mssql') parts.push('IDENTITY(1,1)');
  }
  if (!def.nullable) parts.push('NOT NULL');
  else if (dialect === 'mysql' || dialect === 'mssql') parts.push('NULL');
  if (def.defaultValue.trim() && !def.autoIncrement)
    parts.push(`DEFAULT ${def.defaultValue.trim()}`);
  if (dialect === 'sqlite' && inCreate && primary && def.autoIncrement) {
    // SQLite: only INTEGER PRIMARY KEY AUTOINCREMENT, written on the column itself.
    parts.push('PRIMARY KEY AUTOINCREMENT');
  }
  if (dialect === 'mysql' && def.comment.trim())
    parts.push(`COMMENT ${stringLiteral(def.comment, dialect)}`);
  return parts.join(' ');
}

function pgComment(table: string, column: string, comment: string): string {
  return `COMMENT ON COLUMN ${table}.${quoteIdent(column, 'postgres')} IS ${comment.trim() ? stringLiteral(comment, 'postgres') : 'NULL'}`;
}

export function addColumnSql(
  dialect: DbType,
  database: string,
  table: string,
  def: ColumnDef,
): string[] {
  check(def);
  const t = qualifiedName(database, table, dialect);
  const name = quoteIdent(def.name.trim(), dialect);
  const out = [
    dialect === 'mssql'
      ? // WITH VALUES: existing rows get the default too, as in the other databases.
        `ALTER TABLE ${t} ADD ${name} ${columnBody(def, dialect, false)}${def.defaultValue.trim() ? ' WITH VALUES' : ''}`
      : `ALTER TABLE ${t} ADD COLUMN ${name} ${columnBody(def, dialect, false)}`,
  ];
  if (dialect === 'postgres' && def.comment.trim())
    out.push(pgComment(t, def.name.trim(), def.comment));
  return out;
}

/**
 * SQL Server keeps a default as a named constraint: this batch drops the column's current default
 * constraint, if it has one (its name is looked up).
 */
function mssqlDropDefault(database: string, table: string, column: string): string {
  const full = stringLiteral(
    `${quoteIdent(database, 'mssql')}.${quoteIdent(table, 'mssql')}`,
    'mssql',
  );
  const t = qualifiedName(database, table, 'mssql');
  return (
    `DECLARE @df sysname = (SELECT d.name FROM sys.default_constraints d ` +
    `JOIN sys.columns c ON c.object_id = d.parent_object_id AND c.column_id = d.parent_column_id ` +
    `WHERE d.parent_object_id = OBJECT_ID(${full}) AND c.name = ${stringLiteral(column, 'mssql')}); ` +
    `IF @df IS NOT NULL EXEC('ALTER TABLE ${t.replace(/'/g, "''")} DROP CONSTRAINT [' + @df + ']')`
  );
}

/** Changes a column from `before` to `after`: only what differs (PostgreSQL, SQL Server). */
export function alterColumnSql(
  dialect: DbType,
  database: string,
  table: string,
  before: ColumnDef,
  after: ColumnDef,
): string[] {
  check(after);
  const t = qualifiedName(database, table, dialect);
  const q = (n: string) => quoteIdent(n, dialect);
  const oldName = before.name;
  const newName = after.name.trim();
  const renamed = newName !== oldName;
  const out: string[] = [];
  switch (dialect) {
    case 'mysql':
      // CHANGE redefines the whole column, rename included.
      out.push(
        `ALTER TABLE ${t} CHANGE COLUMN ${q(oldName)} ${q(newName)} ${columnBody(after, dialect, false)}`,
      );
      return out;
    case 'sqlite':
      if (
        after.type.trim() !== before.type.trim() ||
        after.nullable !== before.nullable ||
        after.defaultValue.trim() !== before.defaultValue.trim()
      ) {
        throw new Error('SQLite kan van een kolom alleen de naam wijzigen.');
      }
      if (renamed) out.push(`ALTER TABLE ${t} RENAME COLUMN ${q(oldName)} TO ${q(newName)}`);
      return out;
    case 'postgres': {
      if (renamed) out.push(`ALTER TABLE ${t} RENAME COLUMN ${q(oldName)} TO ${q(newName)}`);
      const c = `ALTER TABLE ${t} ALTER COLUMN ${q(newName)}`;
      if (after.type.trim() !== before.type.trim()) {
        out.push(`${c} TYPE ${after.type.trim()} USING ${q(newName)}::${after.type.trim()}`);
      }
      if (after.nullable !== before.nullable)
        out.push(`${c} ${after.nullable ? 'DROP' : 'SET'} NOT NULL`);
      if (after.defaultValue.trim() !== before.defaultValue.trim()) {
        out.push(
          after.defaultValue.trim()
            ? `${c} SET DEFAULT ${after.defaultValue.trim()}`
            : `${c} DROP DEFAULT`,
        );
      }
      if (after.comment.trim() !== before.comment.trim())
        out.push(pgComment(t, newName, after.comment));
      return out;
    }
    case 'mssql': {
      if (renamed) {
        const from = stringLiteral(
          `${quoteIdent(database, 'mssql')}.${quoteIdent(table, 'mssql')}.${quoteIdent(oldName, 'mssql')}`,
          'mssql',
        );
        out.push(`EXEC sp_rename ${from}, ${stringLiteral(newName, 'mssql')}, 'COLUMN'`);
      }
      const retype = after.type.trim() !== before.type.trim() || after.nullable !== before.nullable;
      const redefault = after.defaultValue.trim() !== before.defaultValue.trim();
      // SQL Server refuses ALTER COLUMN while a default constraint depends on the column, so the
      // default comes off first and goes back on afterwards.
      if (retype || redefault) out.push(mssqlDropDefault(database, table, newName));
      if (retype) {
        out.push(
          `ALTER TABLE ${t} ALTER COLUMN ${q(newName)} ${after.type.trim()} ${after.nullable ? 'NULL' : 'NOT NULL'}`,
        );
      }
      if ((retype || redefault) && after.defaultValue.trim()) {
        out.push(`ALTER TABLE ${t} ADD DEFAULT ${after.defaultValue.trim()} FOR ${q(newName)}`);
      }
      return out;
    }
  }
}

export function dropColumnSql(
  dialect: DbType,
  database: string,
  table: string,
  column: string,
): string[] {
  const t = qualifiedName(database, table, dialect);
  const out: string[] = [];
  if (dialect === 'mssql') out.push(mssqlDropDefault(database, table, column));
  out.push(`ALTER TABLE ${t} DROP COLUMN ${quoteIdent(column, dialect)}`);
  return out;
}

export function createIndexSql(
  dialect: DbType,
  database: string,
  table: string,
  def: IndexDef,
): string[] {
  if (!def.name.trim()) throw new Error('Geef de index een naam.');
  if (def.columns.length === 0) throw new Error('Kies minstens één kolom voor de index.');
  const q = (n: string) => quoteIdent(n, dialect);
  const t = qualifiedName(database, table, dialect);
  const cols = def.columns.map(q).join(', ');
  const unique = def.unique ? 'UNIQUE ' : '';
  // SQLite puts the schema on the index name, not on the table.
  if (dialect === 'sqlite') {
    return [
      `CREATE ${unique}INDEX ${qualifiedName(database, def.name.trim(), dialect)} ON ${q(table)} (${cols})`,
    ];
  }
  // PostgreSQL: the index lives in the table's schema; its name is not qualified.
  return [`CREATE ${unique}INDEX ${q(def.name.trim())} ON ${t} (${cols})`];
}

export function dropIndexSql(
  dialect: DbType,
  database: string,
  table: string,
  name: string,
): string[] {
  const q = (n: string) => quoteIdent(n, dialect);
  const t = qualifiedName(database, table, dialect);
  switch (dialect) {
    case 'mysql':
    case 'mssql':
      return [`DROP INDEX ${q(name)} ON ${t}`];
    case 'postgres':
    case 'sqlite':
      return [`DROP INDEX ${qualifiedName(database, name, dialect)}`];
  }
}

/** A suggested index name: idx_table_col1_col2. */
export function indexName(table: string, columns: string[], unique: boolean): string {
  return `${unique ? 'uq' : 'idx'}_${[table, ...columns].join('_')}`
    .replace(/[^\w]+/g, '_')
    .slice(0, 60);
}

export function createTableSql(
  dialect: DbType,
  database: string,
  table: string,
  columns: (ColumnDef & { primary: boolean })[],
): string[] {
  if (!table.trim()) throw new Error('Geef de tabel een naam.');
  if (columns.length === 0) throw new Error('Een tabel heeft minstens één kolom.');
  const names = columns.map((c) => c.name.trim());
  if (new Set(names).size !== names.length) throw new Error('Twee kolommen hebben dezelfde naam.');
  const q = (n: string) => quoteIdent(n, dialect);
  const t = qualifiedName(database, table.trim(), dialect);
  const pk = columns.filter((c) => c.primary);
  const sqliteInline = dialect === 'sqlite' && pk.length === 1 && pk[0]!.autoIncrement;
  const lines = columns.map((c) => {
    check(c);
    return `  ${q(c.name.trim())} ${columnBody(c, dialect, true, c.primary)}`;
  });
  if (pk.length && !sqliteInline)
    lines.push(`  PRIMARY KEY (${pk.map((c) => q(c.name.trim())).join(', ')})`);
  const out = [`CREATE TABLE ${t} (\n${lines.join(',\n')}\n)`];
  if (dialect === 'postgres') {
    for (const c of columns) if (c.comment.trim()) out.push(pgComment(t, c.name.trim(), c.comment));
  }
  return out;
}

/** The SQL to read a table's indexes; rows are [name, unique, primary, column, position]. */
export function indexListSql(dialect: DbType, database: string, table: string): string {
  const s = (v: string) => stringLiteral(v, dialect);
  switch (dialect) {
    case 'mysql':
      return (
        "SELECT INDEX_NAME, CASE WHEN NON_UNIQUE = 0 THEN 1 ELSE 0 END, CASE WHEN INDEX_NAME = 'PRIMARY' THEN 1 ELSE 0 END, COLUMN_NAME, SEQ_IN_INDEX " +
        `FROM information_schema.STATISTICS WHERE TABLE_SCHEMA = ${s(database)} AND TABLE_NAME = ${s(table)} ORDER BY INDEX_NAME, SEQ_IN_INDEX`
      );
    case 'postgres':
      return (
        'SELECT i.relname, ix.indisunique, ix.indisprimary, a.attname, k.ord FROM pg_index ix ' +
        'JOIN pg_class t ON t.oid = ix.indrelid JOIN pg_class i ON i.oid = ix.indexrelid ' +
        'JOIN pg_namespace n ON n.oid = t.relnamespace ' +
        'CROSS JOIN LATERAL unnest(ix.indkey::int2[]) WITH ORDINALITY AS k(attnum, ord) ' +
        'LEFT JOIN pg_attribute a ON a.attrelid = t.oid AND a.attnum = k.attnum ' +
        `WHERE n.nspname = ${s(database)} AND t.relname = ${s(table)} ORDER BY i.relname, k.ord`
      );
    case 'mssql':
      return (
        'SELECT i.name, i.is_unique, i.is_primary_key, c.name, ic.key_ordinal FROM sys.indexes i ' +
        'JOIN sys.index_columns ic ON ic.object_id = i.object_id AND ic.index_id = i.index_id ' +
        'JOIN sys.columns c ON c.object_id = ic.object_id AND c.column_id = ic.column_id ' +
        `WHERE i.object_id = OBJECT_ID(${s(`${quoteIdent(database, 'mssql')}.${quoteIdent(table, 'mssql')}`)}) AND i.type > 0 AND ic.is_included_column = 0 ` +
        'ORDER BY i.name, ic.key_ordinal'
      );
    case 'sqlite':
      return (
        `SELECT il.name, il."unique", CASE WHEN il.origin = 'pk' THEN 1 ELSE 0 END, ii.name, ii.seqno ` +
        `FROM pragma_index_list(${s(table)}) il JOIN pragma_index_info(il.name) ii ORDER BY il.name, ii.seqno`
      );
  }
}

/** Rows of indexListSql into indexes. */
export function parseIndexes(rows: (string | null)[][]): IndexInfo[] {
  const truthy = (v: string | null | undefined) => ['1', 't', 'true', 'True'].includes(v ?? '');
  const byName = new Map<string, IndexInfo>();
  for (const r of rows) {
    const name = r[0] ?? '';
    let index = byName.get(name);
    if (!index) {
      index = { name, columns: [], unique: truthy(r[1]), primary: truthy(r[2]) };
      byName.set(name, index);
    }
    index.columns.push(r[3] ?? '(expressie)');
  }
  return [...byName.values()].sort(
    (a, b) => Number(b.primary) - Number(a.primary) || a.name.localeCompare(b.name),
  );
}

/**
 * A default as SQL. MySQL and MariaDB report a text default as its value (`Delft`, not
 * `'Delft'`); numbers and expressions such as CURRENT_TIMESTAMP stay as they are. The other
 * databases report SQL already.
 */
export function defaultAsSql(value: string | null, dialect: DbType): string {
  if (value === null) return '';
  if (dialect !== 'mysql') return value;
  if (/^-?\d+(\.\d+)?$/.test(value)) return value;
  if (
    /^(current_timestamp|current_date|current_time|now|localtime|localtimestamp|uuid|curdate|curtime)\b/i.test(
      value,
    )
  )
    return value;
  if (/^\(.*\)$/s.test(value)) return value;
  return stringLiteral(value, dialect);
}

/** A column as the form edits it, from what the server reports. */
export function columnDefOf(
  c: {
    name: string;
    type: string;
    nullable: boolean;
    defaultValue: string | null;
    extra: string;
    comment: string;
  },
  dialect: DbType = 'mysql',
): ColumnDef {
  return {
    name: c.name,
    type: c.type,
    nullable: c.nullable,
    defaultValue: defaultAsSql(c.defaultValue, dialect),
    autoIncrement: /auto_increment|identity/i.test(c.extra),
    comment: c.comment,
  };
}
