import { z } from 'zod';
import { CONNECTION_COLORS } from '../../shared/models';

export const idSchema = z.string().uuid();

/**
 * A connection profile. Servers need a host, port and user; SQLite needs only a file, which goes in
 * `database` (host, port and user are then ignored).
 */
export const fingerprintSchema = z
  .string()
  .regex(/^SHA256:[A-Za-z0-9+/]{43}$/, 'Ongeldige vingerafdruk');

export const sshSettingsSchema = z
  .object({
    host: z.string().trim().min(1, 'SSH-host is verplicht').max(255),
    port: z.number().int().min(1).max(65535),
    user: z.string().trim().min(1, 'SSH-gebruiker is verplicht').max(255),
    auth: z.enum(['password', 'key', 'agent', 'pageant']),
    keyFile: z.string().trim().max(4096),
    hostKey: z.union([z.literal(''), fingerprintSchema]),
  })
  .superRefine((s, ctx) => {
    if (s.auth === 'key' && !s.keyFile)
      ctx.addIssue({ code: 'custom', path: ['keyFile'], message: 'Kies een sleutelbestand' });
  });

export const connectionInputSchema = z
  .object({
    name: z.string().trim().min(1, 'Naam is verplicht').max(100),
    type: z.enum(['mysql', 'postgres', 'mssql', 'sqlite']),
    host: z.string().trim().max(255),
    port: z.number().int().min(0).max(65535),
    database: z.string().trim().max(4096),
    user: z.string().trim().max(255),
    ssl: z.boolean(),
    allowSelfSigned: z.boolean(),
    color: z.enum(CONNECTION_COLORS),
    readOnly: z.boolean().default(false),
    password: z.string().max(1024).optional(),
    savePassword: z.boolean(),
    ssh: sshSettingsSchema.nullable().default(null),
    sshSecret: z.string().max(4096).optional(),
  })
  .superRefine((c, ctx) => {
    if (c.type === 'sqlite') {
      if (!c.database)
        ctx.addIssue({ code: 'custom', path: ['database'], message: 'Kies een databasebestand' });
      return;
    }
    if (!c.host) ctx.addIssue({ code: 'custom', path: ['host'], message: 'Host is verplicht' });
    if (c.port < 1) ctx.addIssue({ code: 'custom', path: ['port'], message: 'Ongeldige poort' });
    if (!c.user)
      ctx.addIssue({ code: 'custom', path: ['user'], message: 'Gebruiker is verplicht' });
    if (c.database.length > 128)
      ctx.addIssue({ code: 'custom', path: ['database'], message: 'Databasenaam is te lang' });
  });

export const optionalIdSchema = idSchema.optional();
export const optionalPasswordSchema = z.string().max(1024).optional();
export const connectSecretsSchema = z
  .object({
    password: z.string().max(1024).optional(),
    sshSecret: z.string().max(4096).optional(),
  })
  .default({});
export const optionalPathSchema = z.string().max(4096).optional();

/**
 * A database, schema, table or view name. Almost any character is allowed (spaces, quotes, unicode),
 * so no trimming or pattern: names travel as parameters or quoted identifiers, never as raw SQL.
 * SQL Server allows 128 characters; MySQL 64, PostgreSQL 63.
 */
export const identifierSchema = z
  .string()
  .min(1, 'Naam ontbreekt')
  .max(128, 'Naam is langer dan 128 tekens')
  .refine((s) => !s.includes('\0'), 'Ongeldig teken in naam');

export const objectKindSchema = z.enum(['table', 'view', 'procedure', 'function']);
export const routineKindSchema = z.enum(['procedure', 'function']);

export const objectActionSchema = z.discriminatedUnion('action', [
  z.object({
    action: z.literal('truncate'),
    database: identifierSchema,
    name: identifierSchema,
    force: z.boolean().optional(),
  }),
  z.object({
    action: z.literal('drop'),
    database: identifierSchema,
    kind: objectKindSchema,
    name: identifierSchema,
    force: z.boolean().optional(),
  }),
  z.object({
    action: z.literal('drop-container'),
    database: identifierSchema,
    force: z.boolean().optional(),
  }),
  z.object({ action: z.literal('create-container'), database: identifierSchema }),
]);

export const whereSchema = z.string().max(10_000, 'Filter is langer dan 10.000 tekens').optional();

export const rowsRequestSchema = z.object({
  offset: z.number().int().min(0).max(Number.MAX_SAFE_INTEGER),
  limit: z.number().int().min(1).max(1000),
  orderBy: z
    .array(z.object({ column: identifierSchema, direction: z.enum(['asc', 'desc']) }))
    .max(16),
  where: whereSchema,
});

/** SQL tab ids are generated by the UI. */
export const tabIdSchema = z.string().regex(/^[A-Za-z0-9_-]{1,64}$/, 'Ongeldig tabblad');

export const runRequestSchema = z.object({
  statements: z.array(z.string().min(1).max(1_000_000)).min(1).max(500),
  database: identifierSchema.optional(),
  maxRows: z.number().int().min(1).max(100_000).nullable(),
});

// A plain value, or SQL written as is (NOW(), DEFAULT, a binary literal of a loaded file).
const cellValue = z.union([
  z.string().max(16_000_000).nullable(),
  z.object({ sql: z.string().min(1).max(40_000_000), label: z.string().max(300).optional() }),
]);
const rowKey = z.record(identifierSchema, z.string().max(65_535));
const rowValues = z.record(identifierSchema, cellValue);

export const changeSetSchema = z
  .object({
    primaryKey: z.array(identifierSchema).min(1).max(16),
    deletes: z.array(z.object({ key: rowKey })).max(5000),
    updates: z.array(z.object({ key: rowKey, values: rowValues })).max(5000),
    inserts: z.array(z.object({ values: rowValues })).max(5000),
  })
  .refine((c) => c.deletes.length + c.updates.length + c.inserts.length > 0, 'Geen wijzigingen');

export const filePathSchema = z.string().min(1).max(4096);

export const sqlImportRequestSchema = z.object({
  file: filePathSchema,
  entry: z.string().min(1).max(4096).optional(),
  password: z.string().max(1024).optional(),
  database: identifierSchema.optional(),
  onError: z.enum(['stop', 'skip']),
});

export const jobIdSchema = z.string().regex(/^[a-z0-9-]{8,64}$/i, 'Ongeldige taak');

const sortKeySchema = z.object({ column: identifierSchema, direction: z.enum(['asc', 'desc']) });

export const exportRequestSchema = z
  .object({
    source: z.discriminatedUnion('kind', [
      z.object({
        kind: z.literal('table'),
        database: identifierSchema,
        table: identifierSchema,
        where: whereSchema,
        orderBy: z.array(sortKeySchema).max(16),
      }),
      z.object({
        kind: z.literal('query'),
        sql: z.string().min(1).max(1_000_000),
        database: identifierSchema.optional(),
      }),
      z.object({
        kind: z.literal('database'),
        database: identifierSchema,
        tables: z.array(identifierSchema).min(1).max(10_000),
        structure: z.boolean(),
        data: z.boolean(),
      }),
      z.object({
        kind: z.literal('keys'),
        database: identifierSchema,
        table: identifierSchema,
        keyColumns: z.array(identifierSchema).min(1).max(16),
        keys: z
          .array(z.array(z.string().max(10_000).nullable()).max(16))
          .min(1)
          .max(10_000),
      }),
      z.object({
        kind: z.literal('values'),
        columns: z.array(z.string().max(1024)).min(1).max(4096),
        numeric: z.array(z.boolean()).max(4096),
        rows: z.array(z.array(z.string().max(10_000_000).nullable())).max(100_000),
      }),
    ]),
    format: z.enum(['csv', 'json', 'sql', 'xlsx', 'markdown']),
    file: z.string().max(4096),
    destination: z.enum(['file', 'clipboard']).optional(),
    csv: z
      .object({ delimiter: z.enum([',', ';', '\t']), header: z.boolean(), bom: z.boolean() })
      .optional(),
    json: z.object({ style: z.enum(['array', 'lines']) }).optional(),
    sql: z
      .object({
        rowsPerInsert: z.number().int().min(1).max(10_000),
        tableName: identifierSchema.optional(),
        createTable: z.boolean().optional(),
        dropTable: z.boolean().optional(),
      })
      .optional(),
    archive: z
      .object({
        kind: z.enum(['gzip', 'zip', '7z']),
        password: z.string().min(1).max(1024).optional(),
      })
      .optional(),
  })
  .superRefine((r, ctx) => {
    if (r.destination === 'clipboard') {
      if (r.format === 'xlsx')
        ctx.addIssue({ code: 'custom', message: 'Excel kan niet naar het klembord.' });
      if (r.archive) ctx.addIssue({ code: 'custom', message: 'Het klembord kan niet ingepakt.' });
    } else if (!filePathSchema.safeParse(r.file).success) {
      ctx.addIssue({ code: 'custom', message: 'Geen bestand gekozen.', path: ['file'] });
    }
  });

export const fileNameSchema = z
  .string()
  .min(1)
  .max(255)
  .refine((n) => !/[\\/]/.test(n), 'Ongeldige naam');

export const cellSaveRequestSchema = z.discriminatedUnion('kind', [
  z.object({
    kind: z.literal('key'),
    database: identifierSchema,
    table: identifierSchema,
    keyColumns: z.array(identifierSchema).min(1).max(16),
    keyValues: z.array(z.string().max(65_535).nullable()).min(1).max(16),
    column: identifierSchema,
    name: z.string().min(1).max(255),
  }),
  z.object({
    kind: z.literal('content'),
    base64: z.string().max(80_000_000),
    name: z.string().min(1).max(255),
  }),
]);
