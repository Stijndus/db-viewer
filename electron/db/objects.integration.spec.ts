/**
 * Tree context menu against real servers (MYSQL_TEST_HOST, PG_TEST_HOST, MSSQL_TEST_HOST) and
 * SQLite: definitions, routine parameters, the call templates actually run, emptying and dropping.
 */
import { promises as fs } from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { afterAll, beforeAll, describe, expect, it, vi } from 'vitest';
import type { DbType, ObjectKind } from '../../shared/models';
import { callTemplate, insertTemplate, selectSql } from '../../shared/object-sql';
import type { ConnectionConfig, DbSession } from './driver';
import { getDriver } from './driver-registry';
import { objectDefinition, routineParams, runObjectAction } from './objects';

vi.setConfig({ testTimeout: 60_000, hookTimeout: 60_000 });

interface Server {
  type: DbType;
  host?: string;
  config: Partial<ConnectionConfig>;
  schema: string;
  /** Creates ctx_t (id, naam), ctx_v, and unless SQLite ctx_p (IN a, OUT b) and ctx_f(a). */
  setup: string[];
  cleanup: string[];
  /** A second container to drop, or null when the dialect cannot. */
  container: { create: string; name: string } | null;
}

const servers: Server[] = [
  {
    type: 'mysql',
    host: process.env['MYSQL_TEST_HOST'],
    config: { port: Number(process.env['MYSQL_TEST_PORT'] ?? 3306), password: 'test123' },
    schema: 'app_dev',
    setup: [
      'CREATE TABLE ctx_t (id int AUTO_INCREMENT PRIMARY KEY, naam varchar(20))',
      "INSERT INTO ctx_t (naam) VALUES ('a'), ('b')",
      'CREATE VIEW ctx_v AS SELECT naam FROM ctx_t',
      'CREATE PROCEDURE ctx_p(IN a int, OUT b int) BEGIN SET b = COALESCE(a, 0) + 1; END',
      'CREATE FUNCTION ctx_f(a int) RETURNS int DETERMINISTIC RETURN COALESCE(a, 0) * 2',
    ],
    cleanup: [
      'DROP VIEW IF EXISTS ctx_v',
      'DROP TABLE IF EXISTS ctx_t',
      'DROP PROCEDURE IF EXISTS ctx_p',
      'DROP FUNCTION IF EXISTS ctx_f',
      'DROP DATABASE IF EXISTS ctx_weg',
    ],
    container: { create: 'CREATE DATABASE ctx_weg', name: 'ctx_weg' },
  },
  {
    type: 'postgres',
    host: process.env['PG_TEST_HOST'],
    config: { port: Number(process.env['PG_TEST_PORT'] ?? 5432), password: 'test123' },
    schema: 'public',
    setup: [
      'CREATE TABLE ctx_t (id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, naam text)',
      "INSERT INTO ctx_t (naam) VALUES ('a'), ('b')",
      'CREATE VIEW ctx_v AS SELECT naam FROM ctx_t',
      'CREATE PROCEDURE ctx_p(IN a int, OUT b int) LANGUAGE plpgsql AS $$ BEGIN b := COALESCE(a, 0) + 1; END $$',
      'CREATE FUNCTION ctx_f(a int, OUT dubbel int) LANGUAGE sql AS $$ SELECT COALESCE(a, 0) * 2 $$',
    ],
    cleanup: [
      'DROP VIEW IF EXISTS ctx_v',
      'DROP TABLE IF EXISTS ctx_t',
      'DROP PROCEDURE IF EXISTS ctx_p',
      'DROP FUNCTION IF EXISTS ctx_f',
      'DROP SCHEMA IF EXISTS ctx_weg CASCADE',
    ],
    container: {
      create: 'CREATE SCHEMA ctx_weg; CREATE TABLE ctx_weg.x (id int)',
      name: 'ctx_weg',
    },
  },
  {
    type: 'mssql',
    host: process.env['MSSQL_TEST_HOST'],
    config: { port: Number(process.env['MSSQL_TEST_PORT'] ?? 1433), password: 'Test123!viewer' },
    schema: 'dbo',
    setup: [
      'CREATE TABLE dbo.ctx_t (id int IDENTITY PRIMARY KEY, naam nvarchar(20))',
      "INSERT INTO dbo.ctx_t (naam) VALUES (N'a'), (N'b')",
      'CREATE VIEW dbo.ctx_v AS SELECT naam FROM dbo.ctx_t',
      'CREATE PROCEDURE dbo.ctx_p @a int, @b int OUTPUT AS SET @b = COALESCE(@a, 0) + 1',
      'CREATE FUNCTION dbo.ctx_f(@a int) RETURNS int AS BEGIN RETURN COALESCE(@a, 0) * 2 END',
    ],
    cleanup: [
      'DROP VIEW IF EXISTS dbo.ctx_v',
      'DROP TABLE IF EXISTS dbo.ctx_t',
      'DROP PROCEDURE IF EXISTS dbo.ctx_p',
      'DROP FUNCTION IF EXISTS dbo.ctx_f',
    ],
    container: null,
  },
  {
    type: 'sqlite',
    host: 'file',
    config: {},
    schema: 'main',
    setup: [
      'CREATE TABLE ctx_t (id integer PRIMARY KEY, naam text)',
      "INSERT INTO ctx_t (naam) VALUES ('a'), ('b')",
      'CREATE VIEW ctx_v AS SELECT naam FROM ctx_t',
    ],
    cleanup: [],
    container: null,
  },
];

for (const server of servers) {
  describe.skipIf(!server.host)(`tree context menu on ${server.type}`, () => {
    let session: DbSession;
    let dir: string;
    const routines = server.type !== 'sqlite';

    const run = async (statements: string[]) => {
      const r = await session.runScript('ctx-test', {
        statements,
        maxRows: 100,
        database: server.type === 'mssql' || server.type === 'sqlite' ? undefined : server.schema,
      });
      const error = r.results.find((x) => x.kind === 'error');
      if (error?.kind === 'error') throw new Error(`${error.sql}: ${error.error.message}`);
      return r.results;
    };
    const names = async () => (await session.listObjects(server.schema)).map((o) => o.name);

    beforeAll(async () => {
      dir = await fs.mkdtemp(path.join(os.tmpdir(), 'dbv-ctx-'));
      if (server.type === 'sqlite') await fs.writeFile(path.join(dir, 'ctx.db'), '');
      session = await getDriver(server.type).open({
        type: server.type,
        host: server.type === 'sqlite' ? '' : server.host!,
        port: 0,
        database: server.type === 'sqlite' ? path.join(dir, 'ctx.db') : 'app_dev',
        user: 'viewer',
        password: '',
        ssl: false,
        allowSelfSigned: false,
        readOnly: false,
        ...server.config,
      } as ConnectionConfig);
      await run(server.cleanup.length ? server.cleanup : ['SELECT 1']);
      for (const statement of server.setup) await run([statement]);
    });

    afterAll(async () => {
      if (session) {
        if (server.cleanup.length) await run(server.cleanup).catch(() => undefined);
        await session.closeEditor('ctx-test');
        await session.close();
      }
      await fs.rm(dir, { recursive: true, force: true });
    });

    it('reads the definition of a table and a view', async () => {
      expect(await objectDefinition(session, server.type, server.schema, 'table', 'ctx_t')).toMatch(
        /CREATE TABLE[\s\S]*ctx_t[\s\S]*naam/i,
      );
      expect(await objectDefinition(session, server.type, server.schema, 'view', 'ctx_v')).toMatch(
        /ctx_v[\s\S]*SELECT[\s\S]*naam/i,
      );
    });

    it.runIf(routines)('reads routine definitions and parameters', async () => {
      expect(
        await objectDefinition(session, server.type, server.schema, 'procedure', 'ctx_p'),
      ).toMatch(/PROCEDURE[\s\S]*ctx_p/i);
      expect(
        await objectDefinition(session, server.type, server.schema, 'function', 'ctx_f'),
      ).toMatch(/FUNCTION[\s\S]*ctx_f/i);

      const p = await routineParams(session, server.type, server.schema, 'procedure', 'ctx_p');
      expect(p.map((x) => [x.name, x.mode])).toEqual([
        ['a', 'in'],
        ['b', server.type === 'mssql' ? 'inout' : 'out'],
      ]);
      expect(p[0]?.type).toMatch(/int/i);
    });

    it('reports a missing object clearly', async () => {
      await expect(
        objectDefinition(session, server.type, server.schema, 'view', 'bestaat_niet'),
      ).rejects.toThrow(/niet gevonden|doesn't exist|does not exist|bestaat niet/i);
    });

    it('runs the SELECT and INSERT templates', async () => {
      const cols = await session.listColumns(server.schema, 'ctx_t');
      const insert = insertTemplate(server.type, server.schema, 'ctx_t', cols);
      // The id is filled by the server (SQLite: INTEGER PRIMARY KEY takes NULL as "next").
      if (server.type !== 'sqlite') expect(insert).not.toMatch(/"id"|`id`|\[id\]/);
      await run([insert]);
      const [result] = await run([selectSql(server.type, server.schema, 'ctx_t')]);
      expect(result?.kind === 'rows' && result.rows).toHaveLength(3);
    });

    it.runIf(routines)('runs the call templates as they are', async () => {
      for (const kind of ['procedure', 'function'] as const) {
        const name = kind === 'procedure' ? 'ctx_p' : 'ctx_f';
        const params = await routineParams(session, server.type, server.schema, kind, name);
        const sql = callTemplate(server.type, server.schema, kind, name, params);
        // SQL Server runs a batch as one statement; the others split on semicolons.
        const statements =
          server.type === 'mssql' ? [sql] : sql.split(/;\s*(?:\n|$)/).filter((s) => s.trim());
        const results = await run(statements);
        const last = results.at(-1);
        expect(last?.kind, sql).toBe('rows');
        const value = last?.kind === 'rows' ? last.rows[0]?.[0] : undefined;
        expect(value, sql).toBe(kind === 'procedure' ? '1' : '0');
      }
    });

    it('empties a table', async () => {
      await runObjectAction(session, server.type, false, {
        action: 'truncate',
        database: server.schema,
        name: 'ctx_t',
      });
      const [result] = await run([selectSql(server.type, server.schema, 'ctx_t')]);
      expect(result?.kind === 'rows' && result.rows).toHaveLength(0);
    });

    it('refuses on a read-only connection', async () => {
      await expect(
        runObjectAction(session, server.type, true, {
          action: 'drop',
          database: server.schema,
          kind: 'table',
          name: 'ctx_t',
        }),
      ).rejects.toThrow(/alleen-lezen/);
      expect(await names()).toContain('ctx_t');
    });

    it('drops views, routines and tables', async () => {
      const kinds: [ObjectKind, string][] = [
        ['view', 'ctx_v'],
        ...(routines
          ? ([
              ['procedure', 'ctx_p'],
              ['function', 'ctx_f'],
            ] as [ObjectKind, string][])
          : []),
        ['table', 'ctx_t'],
      ];
      for (const [kind, name] of kinds) {
        await runObjectAction(session, server.type, false, {
          action: 'drop',
          database: server.schema,
          kind,
          name,
        });
      }
      const own = new Set(kinds.map(([, name]) => name));
      expect((await names()).filter((n) => own.has(n))).toEqual([]);
    });

    it('passes on the server error when something cannot be dropped', async () => {
      await expect(
        runObjectAction(session, server.type, false, {
          action: 'drop',
          database: server.schema,
          kind: 'table',
          name: 'bestaat_niet',
        }),
      ).rejects.toThrow(/bestaat_niet|unknown table|does not exist|no such table/i);
    });

    it.runIf(server.container)('drops a whole database or schema', async () => {
      const container = server.container!;
      await run(container.create.split('; '));
      expect((await session.listDatabases()).map((d) => d.name)).toContain(container.name);
      await runObjectAction(session, server.type, false, {
        action: 'drop-container',
        database: container.name,
      });
      expect((await session.listDatabases()).map((d) => d.name)).not.toContain(container.name);
    });
  });
}
