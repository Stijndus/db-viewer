/** "Systeem" follows the OS: Donker or Licht. */
export const SYSTEM = 'system';

export function themeById(id: string): Theme {
  return THEMES.find((t) => t.id === id) ?? donker;
}

// ── Contrast (WCAG 2.1), used by the tests ─────────────────────────

function channel(c: number): number {
  const s = c / 255;
  return s <= 0.03928 ? s / 12.92 : ((s + 0.055) / 1.055) ** 2.4;
}

export function luminance(hex: string): number {
  const m = /^#([0-9a-f]{2})([0-9a-f]{2})([0-9a-f]{2})$/i.exec(hex);
  if (!m) throw new Error(`Geen hexkleur: ${hex}`);
  const [r, g, b] = [m[1]!, m[2]!, m[3]!].map((x) => channel(parseInt(x, 16)));
  return 0.2126 * r! + 0.7152 * g! + 0.0722 * b!;
}

export function contrast(a: string, b: string): number {
  const [x, y] = [luminance(a), luminance(b)].sort((p, q) => q - p);
  return (x! + 0.05) / (y! + 0.05);
}

/** Puts a theme's colours on the page (CSS variables on <html>). */
export function applyTheme(theme: Theme, root: HTMLElement = document.documentElement): void {
  for (const token of TOKENS) root.style.setProperty(`--${token}`, theme.colors[token]);
  root.style.colorScheme = theme.dark ? 'dark' : 'light';
  root.dataset['theme'] = theme.id;
}

export const THEME_KEY = 'dbv.theme';

/** The saved choice, or the system/dark default; safe when storage is unavailable. */
export function savedThemeChoice(): string {
  try {
    return localStorage.getItem(THEME_KEY) ?? 'donker';
  } catch {
    return 'donker';
  }
}

export function resolveTheme(choice: string, systemDark: boolean): Theme {
  if (choice === SYSTEM) return themeById(systemDark ? 'donker' : 'licht');
  return themeById(choice);
}
